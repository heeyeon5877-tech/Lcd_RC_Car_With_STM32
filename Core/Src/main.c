static float ClampFloat(float value, float min_value, float max_value)
{
    if (value < min_value) return min_value;
    if (value > max_value) return max_value;
    return value;
}

int16_t Tilt_ToScreenX(float accel_value)
{
    const float input_min = -60.0f;
    const float input_max = 60.0f;
    const float deadzone = 6.0f;
    const float span = (float)(ILI9341_WIDTH - FACE_WIDTH);

    float value = ClampFloat(accel_value, input_min, input_max);
    if (fabsf(value) < deadzone) value = 0.0f;

    // -60 ~ +60 -> -1 ~ +1 로 정규화
    float normalized = value / input_max;
    normalized = ClampFloat(normalized, -1.0f, 1.0f);

    float eased = normalized * normalized * normalized;
    float t = (eased + 1.0f) * 0.5f;

    return (int16_t)(t * span + 0.5f);
}

int16_t Tilt_ToScreenY(float accel_value)
{
    const float input_min = -60.0f;
    const float input_max = 60.0f;
    const float deadzone = 6.0f;
    const float span = (float)(ILI9341_HEIGHT - FACE_HEIGHT);

    float value = ClampFloat(accel_value, input_min, input_max);
    if (fabsf(value) < deadzone) value = 0.0f;

    float normalized = value / input_max;
    normalized = ClampFloat(normalized, -1.0f, 1.0f);

    float eased = normalized * normalized * normalized;
    float t = (eased + 1.0f) * 0.5f;

    return (int16_t)(t * span + 0.5f);
}

